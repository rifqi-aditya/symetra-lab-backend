-- Normalize existing order statuses in orders table to:
-- PENDING, PROCESSED, SHIPPED, COMPLETED, CANCELLED

UPDATE orders
SET status = CASE
    WHEN UPPER(TRIM(status)) IN ('UNPAID', 'PENDING', 'QUEUED') THEN 'PENDING'
    WHEN UPPER(TRIM(status)) IN ('READY_TO_SHIP', 'PROCESSED', 'PRINTING', 'IN_PRODUCTION', 'TO_SHIP') THEN 'PROCESSED'
    WHEN UPPER(TRIM(status)) IN ('SHIPPED') THEN 'SHIPPED'
    WHEN UPPER(TRIM(status)) IN ('COMPLETED', 'TO_CONFIRM_RECEIVE', 'DELIVERED', 'DONE') THEN 'COMPLETED'
    WHEN UPPER(TRIM(status)) IN ('CANCELLED', 'IN_CANCEL', 'REFUNDED', 'TO_RETURN') THEN 'CANCELLED'
    ELSE status
END
WHERE status IS NOT NULL;
